it('supports cancellation without assuming that publication was rolled back', async () => {
  let reject!: (reason: Error) => void
  vi.mocked(commitCreation).mockReturnValueOnce(new Promise((_, fail) => { reject = fail }))
  render(<ProjectCreation onClose={vi.fn()} onCreated={vi.fn()} />)
  const user = await prepare()
  await user.dblClick(screen.getByRole('button', { name: 'Confirm and create project' }))
  expect(commitCreation).toHaveBeenCalledTimes(1)
  expect(screen.getByRole('button', { name: 'Close dialog' })).toBeDisabled()
  await user.click(screen.getByRole('button', { name: 'Cancel creation' }))
  expect(vi.mocked(commitCreation).mock.calls[0][1].aborted).toBe(true)
  await act(async () => reject(new Error('cancelled')))
  expect(await screen.findByRole('alert')).toHaveTextContent('Files may already have been published')
  expect(screen.getByRole('button', { name: 'Back to options' })).toBeDisabled()
  vi.mocked(getCreationOutcome).mockResolvedValueOnce({ ...created, created: false, registered: false, state: null, code: 'creation_pending', message: 'No completed outcome available.' })
  await user.click(screen.getByRole('button', { name: 'Check creation outcome' }))
  expect(await screen.findByRole('alert')).toHaveTextContent('No completed outcome available')
  expect(commitCreation).toHaveBeenCalledTimes(1)
  expect(getCreationOutcome).toHaveBeenCalledExactlyOnceWith('held-review')
  expect(screen.getByRole('button', { name: 'Back to options' })).toBeDisabled()
})

