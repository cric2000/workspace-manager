import { act, render, screen, within } from '@testing-library/react'
import userEvent from '@testing-library/user-event'
import { beforeEach, describe, expect, it, vi } from 'vitest'
import { ProjectRegistry } from './ProjectRegistry'
import { ProjectSource } from '../../bindings/workspace-manager/internal/domain/models'
import { commitRegistration, listProjects, reviewRegistration, type ProjectView, type RegistrationReview, type RegistryResult, type Report } from '../services/projects'

vi.mock('../services/projects', () => ({ commitRegistration: vi.fn(), listProjects: vi.fn(), reviewRegistration: vi.fn() }))
const timestamp = '2026-10-31T10:00:00Z'
const report: Report = { path: '/code/api', partial: false, stacks: [], candidates: [{ label: 'Go API', program: 'go', arguments: ['run', '.'], workingDirectory: '/code/api', reason: 'main', confidence: 'source' }], findings: [], tools: [] }
const view: ProjectView = { revision: 'a'.repeat(64), project: { id: '1'.repeat(32), name: 'API', path: report.path, source: ProjectSource.SourceImported, createdAt: timestamp, updatedAt: timestamp, commands: [{ id: '2'.repeat(32), configuration: { name: 'Go API', executable: '/usr/bin/go', arguments: ['run', '.', ''], workingDirectory: report.path }, approval: { fingerprint: 'b'.repeat(64), approvedAt: timestamp } }] } }
const review: RegistrationReview = { token: 'review-1', expiresAt: '2026-10-31T10:05:00Z', project: view.project, editing: false }
const ready = (projects: ProjectView[] = []): RegistryResult => ({ state: { projects }, code: '', message: '', committed: false })

describe('reviewed project registration', () => {
  beforeEach(() => {
    vi.mocked(listProjects).mockReset().mockResolvedValue(ready())
    vi.mocked(reviewRegistration).mockReset().mockResolvedValue({ review, code: '', message: '' })
    vi.mocked(commitRegistration).mockReset().mockResolvedValue({ ...ready([view]), committed: true })
  })

  it('reviews a selected suggestion, preserves literal and empty argv, and saves only the review token', async () => {
    const user = userEvent.setup()
    render(<ProjectRegistry report={report} candidate={report.candidates![0]} />)
    await user.click(await screen.findByRole('button', { name: 'Configure project' }))
    expect(screen.getByLabelText('Executable or tool')).toHaveValue('go')
    await user.click(screen.getByRole('button', { name: 'Add argument to command 1' }))
    expect(screen.getByLabelText('Command 1 argument 3')).toHaveValue('')
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    expect(reviewRegistration).toHaveBeenCalledWith(expect.objectContaining({ id: '', path: '/code/api', commands: [expect.objectContaining({ configuration: expect.objectContaining({ arguments: ['run', '.', ''] }) })] }))
    const dialog = await screen.findByRole('dialog')
    expect(dialog).toHaveTextContent('/usr/bin/go')
    expect(dialog).toHaveTextContent('""')
    expect(commitRegistration).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Approve and save project' }))
    expect(commitRegistration).toHaveBeenCalledExactlyOnceWith('review-1')
    expect(await screen.findByRole('article', { name: 'Registered project API' })).toHaveTextContent('Configuration approved')
    expect(screen.getByText('Project configuration saved. No command was started.')).toBeInTheDocument()
    expect(screen.queryByRole('dialog')).not.toBeInTheDocument()
  })

  it('requires a new review after returning to edit and lets a no-command registration be cancelled', async () => {
    const user = userEvent.setup()
    render(<ProjectRegistry report={report} candidate={null} />)
    await user.click(await screen.findByRole('button', { name: 'Configure project' }))
    expect(screen.getByText('This project will be registered without startup commands.')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    await user.click(await screen.findByRole('button', { name: 'Back to configuration' }))
    await user.clear(screen.getByLabelText('Project name')); await user.type(screen.getByLabelText('Project name'), 'Changed')
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    expect(reviewRegistration).toHaveBeenLastCalledWith(expect.objectContaining({ name: 'Changed', commands: [] }))
    await user.click(screen.getByRole('button', { name: 'Close dialog' }))
    expect(commitRegistration).not.toHaveBeenCalled()
  })

  it('reopens saved commands with revision and identity, excludes approval from drafts, and supports ordering/removal', async () => {
    const user = userEvent.setup()
    vi.mocked(listProjects).mockResolvedValueOnce(ready([view]))
    render(<ProjectRegistry report={null} candidate={null} />)
    await user.click(await screen.findByRole('button', { name: 'Edit project API' }))
    expect(screen.getByLabelText('Command 1 argument 3')).toHaveValue('')
    await user.click(screen.getByRole('button', { name: 'Add startup command' }))
    const second = screen.getByRole('group', { name: 'Startup command 2' })
    await user.type(within(second).getByLabelText('Name'), 'Worker')
    await user.type(within(second).getByLabelText('Executable or tool'), '/usr/bin/worker')
    await user.click(screen.getByRole('button', { name: 'Move command 2 up' }))
    await user.click(screen.getByRole('button', { name: 'Remove command 2' }))
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    expect(reviewRegistration).toHaveBeenCalledWith(expect.objectContaining({ id: view.project.id, revision: view.revision, commands: [{ id: '', configuration: expect.objectContaining({ name: 'Worker', executable: '/usr/bin/worker' }) }] }))
    expect(JSON.stringify(vi.mocked(reviewRegistration).mock.calls)).not.toContain('approval')
  })

  it('retains a conflicting draft and blocks another save until the latest project is reopened', async () => {
    const user = userEvent.setup()
    vi.mocked(listProjects).mockResolvedValueOnce(ready([view]))
    vi.mocked(reviewRegistration).mockResolvedValueOnce({ review: null, code: 'conflict', message: 'Changed in another window. Reload projects.' })
    render(<ProjectRegistry report={null} candidate={null} />)
    await user.click(await screen.findByRole('button', { name: 'Edit project API' }))
    await user.type(screen.getByLabelText('Project name'), ' draft')
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Changed in another window')
    expect(screen.getByLabelText('Project name')).toHaveValue('API draft')
    expect(screen.getByRole('button', { name: 'Review configuration' })).toBeDisabled()
    expect(commitRegistration).not.toHaveBeenCalled()
  })

  it('blocks duplicate saves and checks the same token after a lost response', async () => {
    const user = userEvent.setup()
    let reject!: (reason: unknown) => void
    vi.mocked(commitRegistration).mockReturnValueOnce(new Promise((_, rejectPromise) => { reject = rejectPromise }))
    render(<ProjectRegistry report={report} candidate={report.candidates![0]} />)
    await user.click(await screen.findByRole('button', { name: 'Configure project' }))
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    await user.dblClick(await screen.findByRole('button', { name: 'Approve and save project' }))
    expect(commitRegistration).toHaveBeenCalledTimes(1)
    await act(async () => reject(new Error('secret=token /private/path')))
    expect(screen.getByRole('alert')).toHaveTextContent('save response was lost')
    expect(screen.getByRole('button', { name: 'Back to configuration' })).toBeDisabled()
    expect(screen.queryByText(/secret=token/)).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Check save outcome' }))
    expect(vi.mocked(commitRegistration).mock.calls).toEqual([['review-1'], ['review-1']])
    await screen.findByRole('article', { name: 'Registered project API' })
  })

  it('returns changed reviews to the editable draft and surfaces storage failures without partial lists', async () => {
    const user = userEvent.setup()
    vi.mocked(listProjects).mockRejectedValueOnce(new Error('private=secret'))
    render(<ProjectRegistry report={report} candidate={null} />)
    expect(await screen.findByRole('alert')).toHaveTextContent('Could not connect to project storage')
    expect(screen.getByRole('button', { name: 'Configure project' })).toBeDisabled()
    await user.click(screen.getByRole('button', { name: 'Reload registered projects' }))
    await user.click(screen.getByRole('button', { name: 'Configure project' }))
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    vi.mocked(commitRegistration).mockResolvedValueOnce({ state: null, committed: false, code: 'review_changed', message: 'Executable changed. Review again.' })
    await user.click(await screen.findByRole('button', { name: 'Approve and save project' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('Executable changed')
    expect(screen.getByLabelText('Project name')).toHaveValue('api')
    expect(screen.getByRole('button', { name: 'Review configuration' })).toBeEnabled()
  })

  it('requires reload if a lost save outcome expires or the service restarts', async () => {
    const user = userEvent.setup()
    vi.mocked(commitRegistration).mockRejectedValueOnce(new Error('transport lost')).mockResolvedValueOnce({ state: null, committed: false, code: 'review_changed', message: 'Review unavailable.' })
    render(<ProjectRegistry report={report} candidate={null} />)
    await user.click(await screen.findByRole('button', { name: 'Configure project' }))
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    await user.click(await screen.findByRole('button', { name: 'Approve and save project' }))
    await user.click(await screen.findByRole('button', { name: 'Check save outcome' }))
    expect(await screen.findByRole('alert')).toHaveTextContent('reload registered projects before making another change')
    expect(screen.getByRole('button', { name: 'Review configuration' })).toBeDisabled()
    expect(reviewRegistration).toHaveBeenCalledTimes(1)
  })

  it('reviews environment references, timing, readiness, editor, preview and a literal stop action before saving', async () => {
    const user = userEvent.setup()
    vi.mocked(reviewRegistration).mockImplementation(async draft => ({ code: '', message: '', review: { ...review, project: { ...view.project, name: draft.name, preferences: draft.preferences, commands: draft.commands?.map((command, index) => ({ ...command, id: String(index), configuration: { ...command.configuration, executable: '/usr/bin/go' } })) } } }))
    render(<ProjectRegistry report={report} candidate={report.candidates![0]} />)
    await user.click(await screen.findByRole('button', { name: 'Configure project' }))
    await user.type(screen.getByLabelText(/Preview URL/), 'http://localhost:8123/docs')
    await user.click(screen.getByLabelText('Configure an editor action'))
    await user.type(screen.getByLabelText('Editor executable or tool'), '/usr/bin/code')
    expect(screen.getByLabelText('Editor argument 1')).toHaveValue('/code/api')
    await user.click(screen.getByText('Command 1 environment and startup behavior'))
    await user.clear(screen.getByLabelText('Command 1 launch delay (seconds)')); await user.type(screen.getByLabelText('Command 1 launch delay (seconds)'), '3')
    await user.click(screen.getByRole('button', { name: 'Add Command 1 environment file' }))
    await user.type(screen.getByLabelText('Command 1 environment file 1'), '.env.local')
    await user.selectOptions(screen.getByLabelText('Command 1 readiness'), 'http')
    await user.type(screen.getByLabelText('Command 1 readiness URL'), 'http://127.0.0.1:8123/health')
    await user.selectOptions(screen.getByLabelText('Command 1 stop signal'), 'SIGINT')
    await user.click(screen.getByLabelText('Configure Command 1 stop action'))
    await user.type(screen.getByLabelText('Command 1 stop action executable or tool'), '/usr/bin/docker')
    await user.click(screen.getByRole('button', { name: 'Add Command 1 stop action argument' }))
    await user.type(screen.getByLabelText('Command 1 stop action argument 1'), 'literal ; $HOME')
    await user.click(screen.getByRole('button', { name: 'Add Command 1 stop action argument' }))
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    const sent = vi.mocked(reviewRegistration).mock.calls[0][0]
    expect(sent.preferences).toEqual({ previewUrl: 'http://localhost:8123/docs', editor: { executable: '/usr/bin/code', arguments: ['/code/api'], workingDirectory: '/code/api' } })
    expect(sent.commands![0].configuration.runtime).toEqual(expect.objectContaining({ delaySeconds: 3, environmentFiles: ['.env.local'], readiness: expect.objectContaining({ kind: 'http', url: 'http://127.0.0.1:8123/health', expectedStatus: 200 }), stop: expect.objectContaining({ signal: 'SIGINT', graceSeconds: 10, action: expect.objectContaining({ arguments: ['literal ; $HOME', ''] }) }) }))
    const dialog = screen.getByRole('dialog')
    expect(dialog).toHaveTextContent('HTTP 200: http://127.0.0.1:8123/health')
    expect(dialog).toHaveTextContent('Timeout 30s; interval 1s')
    expect(dialog).toHaveTextContent('SIGINT; 10s grace; no automatic force stop')
    expect(dialog).toHaveTextContent('".env.local"')
    expect(screen.getByRole('region', { name: 'Editor action' })).toHaveTextContent('/usr/bin/code')
    expect(screen.getByRole('region', { name: 'Stop action' })).toHaveTextContent('"literal ; $HOME"')
    expect(commitRegistration).not.toHaveBeenCalled()
    await user.click(screen.getByRole('button', { name: 'Approve and save project' }))
    expect(commitRegistration).toHaveBeenCalledExactlyOnceWith('review-1')
  })

  it('reopens settings independently and excludes preference approval from edited drafts', async () => {
    const user = userEvent.setup()
    const configured = structuredClone(view)
    configured.project.preferences = { previewUrl: 'http://localhost:8123/docs', editor: { executable: '/usr/bin/code', arguments: ['/code/api'], workingDirectory: '/code/api' }, approval: { fingerprint: 'old', approvedAt: timestamp } }
    configured.project.commands![0].configuration.runtime = { environmentFiles: ['.env'], delaySeconds: 4, readiness: { kind: 'tcp', host: '::1', port: 8123, timeoutSeconds: 20, intervalSeconds: 2 }, stop: { signal: 'SIGTERM', graceSeconds: 15, action: { executable: '/usr/bin/docker', arguments: ['down'], workingDirectory: '/code/api' } } }
    vi.mocked(listProjects).mockResolvedValueOnce(ready([configured]))
    render(<ProjectRegistry report={null} candidate={null} />)
    await user.click(await screen.findByRole('button', { name: 'Edit project API' }))
    expect(screen.getByLabelText(/Preview URL/)).toHaveValue('http://localhost:8123/docs')
    expect(screen.getByLabelText('Editor argument 1')).toHaveValue('/code/api')
    await user.click(screen.getByText('Command 1 environment and startup behavior'))
    expect(screen.getByLabelText('Command 1 readiness host')).toHaveValue('::1')
    expect(screen.getByLabelText('Command 1 stop grace (seconds)')).toHaveValue(15)
    await user.type(screen.getByLabelText('Command 1 environment file 1'), '.changed')
    await user.type(screen.getByLabelText('Command 1 stop action argument 1'), '-changed')
    await user.type(screen.getByLabelText('Editor argument 1'), '-changed')
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    const sent = vi.mocked(reviewRegistration).mock.calls[0][0]
    expect(JSON.stringify(sent)).not.toContain('approval')
    expect(sent.preferences?.editor?.arguments).toEqual(['/code/api-changed'])
    expect(configured.project.preferences.editor!.arguments).toEqual(['/code/api'])
    expect(configured.project.commands![0].configuration.runtime!.environmentFiles).toEqual(['.env'])
    expect(configured.project.commands![0].configuration.runtime!.stop!.action!.arguments).toEqual(['down'])
  })

  it('switches readiness kinds without retaining inactive fields and clears optional actions/settings', async () => {
    const user = userEvent.setup()
    render(<ProjectRegistry report={report} candidate={report.candidates![0]} />)
    await user.click(await screen.findByRole('button', { name: 'Configure project' }))
    await user.click(screen.getByText('Command 1 environment and startup behavior'))
    await user.selectOptions(screen.getByLabelText('Command 1 readiness'), 'http')
    await user.type(screen.getByLabelText('Command 1 readiness URL'), 'http://localhost:8123/old')
    await user.selectOptions(screen.getByLabelText('Command 1 readiness'), 'tcp')
    await user.clear(screen.getByLabelText('Command 1 readiness port')); await user.type(screen.getByLabelText('Command 1 readiness port'), '8123')
    expect(screen.queryByLabelText('Command 1 readiness URL')).not.toBeInTheDocument()
    await user.selectOptions(screen.getByLabelText('Command 1 stop signal'), 'SIGINT')
    await user.click(screen.getByLabelText('Configure Command 1 stop action'))
    await user.selectOptions(screen.getByLabelText('Command 1 stop signal'), '')
    expect(screen.queryByLabelText('Command 1 stop action executable or tool')).not.toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    expect(vi.mocked(reviewRegistration).mock.calls[0][0].commands![0].configuration.runtime).toEqual({ readiness: { kind: 'tcp', host: '127.0.0.1', port: 8123, timeoutSeconds: 30, intervalSeconds: 1 }, stop: null })
    await user.click(screen.getByRole('button', { name: 'Back to configuration' }))
    await user.click(screen.getByText('Command 1 environment and startup behavior'))
    await user.click(screen.getByRole('button', { name: 'Clear Command 1 runtime settings' }))
    await user.click(screen.getByRole('button', { name: 'Review configuration' }))
    expect(vi.mocked(reviewRegistration).mock.calls[1][0].commands![0].configuration.runtime).toBeNull()
  })
})
